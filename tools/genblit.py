#!/usr/bin/env python3
"""
Generates src/blit.s - the 1bpp software framebuffer -> SMS VDP blitter.

Layout
------
The game renders into an Arduboy-style column-major 1bpp framebuffer:

    screenBuffer[page * FB_W + x],  bit (y & 7)

one byte = 1 pixel wide x 8 pixels tall.  The SMS has no framebuffer, so every
frame that buffer is converted into 8x8 4bpp tiles and pushed through the VDP
data port.  The picture is magnified 2x2, therefore

    one destination tile  =  4 source columns  x  4 source rows
                          =  4 source bytes, one nibble of each

Two tricks keep this affordable:

1.  *Only bitplane 0 is ever written.*  Planes 1..3 are zeroed once at startup
    and never touched again, so a tile costs 8 VDP writes instead of 32.  The
    palette is set so colour 1 = white and colour 0 = black.
    Because the VDP address has to be re-latched for every plane-0 byte (they
    sit 4 bytes apart) consecutive data writes end up ~44 cycles apart, which
    also satisfies the "pace VRAM writes during active display" rule for free.

2.  *Dirty-tile tracking.*  A copy of the previous frame is kept; a tile whose
    4 source nibbles did not change is skipped.  Large parts of a typical view
    (the static ceiling/floor dither, the HUD) survive untouched.

Bit shuffling
-------------
For destination row k the 4 source bits (one per source column) are gathered
into a nibble with `srl r / rla` and expanded to the doubled 8 bit pattern
through a 16 entry table at a fixed 256-byte-aligned RAM address (SPREAD_ADDR),
so the lookup is just `ld l,a / ld a,(hl)`.
"""

import sys

FB_W = 104                     # framebuffer width in pixels (= bytes per page)
FB_PAGES = 8                   # framebuffer height / 8
TILES_X = FB_W // 4            # destination tiles across
TILES_Y = FB_PAGES * 2         # destination tiles down
ROW_STRIDE = TILES_X * 32      # bytes of VRAM per destination tile row
VRAM_BASE = 0x4000             # tile 0, write command

SPREAD_ADDR = 0xC000           # 256 byte aligned; see --data-loc in the Makefile

out = []
def e(s=""):
    out.append(s)


e("; ---------------------------------------------------------------------------")
e("; blit.s - GENERATED by tools/genblit.py, do not edit by hand")
e("; 1bpp %dx%d framebuffer -> %dx%d SMS tiles, magnified 2x2" %
  (FB_W, FB_PAGES * 8, TILES_X, TILES_Y))
e("; ---------------------------------------------------------------------------")
e("        .module blit")
e("        .globl _Platform_Present")
e("        .globl _Platform_PresentFull")
e("        .globl _screenBuffer")
e("        .globl _prevBuffer")
e("        .globl _blitTileCount")
e()
e("VDPCTRL = 0xBF")
e("VDPDATA = 0xBE")
e("SPREADHI = 0x%02X" % (SPREAD_ADDR >> 8))
e()
e("        .area _DATA")
e("_prevBuffer::   .ds %d" % (FB_W * FB_PAGES))
e("_blitTileCount::.ds 2            ; tiles pushed last call (profiling hook)")
e("bl_src:         .ds 2            ; walking source pointer (diff pass)")
e("bl_prv:         .ds 2            ; walking previous-frame pointer")
e("bl_srcrow:      .ds 2            ; start of the page row being emitted")
e("bl_alo:         .ds 2            ; VRAM addr, low tile of current column")
e("bl_ahi:         .ds 2            ; VRAM addr, high tile of current column")
e("bl_cnt:         .ds 1")
e("bl_page:        .ds 1")
e("bl_force:       .ds 1            ; !=0 -> ignore the dirty test")
e("bl_rows:        .ds 8            ; 4 row bytes low tile, 4 row bytes high tile")
e("bl_flags:       .ds %d" % TILES_X)
e()
e("        .area _CODE")
e()

# ---------------------------------------------------------------------------
# Entry points
# ---------------------------------------------------------------------------
e("_Platform_PresentFull::")
e("        ld a,#1")
e("        jr present_entry")
e("_Platform_Present::")
e("        xor a")
e("present_entry:")
e("        ld (bl_force),a")
e("        ld hl,#0")
e("        ld (_blitTileCount),hl")
e("        ld hl,#_screenBuffer")
e("        ld (bl_src),hl")
e("        ld hl,#_prevBuffer")
e("        ld (bl_prv),hl")
e("        xor a")
e("        ld (bl_page),a")
e("page_loop:")
e("        ld hl,(bl_src)")
e("        ld (bl_srcrow),hl")
e("        call diff_page")
e("        call emit_page")
e("        ld a,(bl_page)")
e("        inc a")
e("        ld (bl_page),a")
e("        cp #%d" % FB_PAGES)
e("        jr c,page_loop")
e("        ret")
e()

# ---------------------------------------------------------------------------
# diff_page
# ---------------------------------------------------------------------------
e("diff_page:")
e("        ld a,(bl_force)")
e("        or a")
e("        jr nz,diff_forced")
e("        ld hl,(bl_src)")
e("        ld de,(bl_prv)")
e("        ld iy,#bl_flags")
e("        ld a,#%d" % TILES_X)
e("        ld (bl_cnt),a")
e("diff_col:")
for i in range(4):
    e("        ld a,(de)")
    e("        xor (hl)")
    if i:
        e("        or c")
    e("        ld c,a")
    e("        ld a,(hl)")
    e("        ld (de),a")
    e("        inc hl")
    e("        inc de")
e("        ld b,#0")
e("        ld a,c")
e("        and #0x0F")
e("        jr z,diff_nolo")
e("        inc b")
e("diff_nolo:")
e("        ld a,c")
e("        and #0xF0")
e("        jr z,diff_nohi")
e("        set 1,b")
e("diff_nohi:")
e("        ld 0(iy),b")
e("        inc iy")
e("        ld a,(bl_cnt)")
e("        dec a")
e("        ld (bl_cnt),a")
e("        jr nz,diff_col")
e("        ld (bl_src),hl")
e("        ld (bl_prv),de")
e("        ret")
e("diff_forced:")
e("        ld hl,(bl_src)")
e("        ld de,(bl_prv)")
e("        ld bc,#%d" % FB_W)
e("        ldir")
e("        ld (bl_src),hl")
e("        ld (bl_prv),de")
e("        ld hl,#bl_flags")
e("        ld b,#%d" % TILES_X)
e("diff_fill:")
e("        ld (hl),#3")
e("        inc hl")
e("        djnz diff_fill")
e("        ret")
e()

# ---------------------------------------------------------------------------
# emit_page
# ---------------------------------------------------------------------------
e("emit_page:")
e("        ld a,(bl_page)")
e("        add a,a")
e("        add a,a")
e("        ld l,a")
e("        ld h,#0")
e("        ld de,#page_addr_tbl")
e("        add hl,de")
e("        ld e,(hl)")
e("        inc hl")
e("        ld d,(hl)")
e("        inc hl")
e("        ld (bl_alo),de")
e("        ld e,(hl)")
e("        inc hl")
e("        ld d,(hl)")
e("        ld (bl_ahi),de")
e("        ld iy,#bl_flags")
e("        ld a,#%d" % TILES_X)
e("        ld (bl_cnt),a")
e("emit_col:")
e("        ld a,0(iy)")
e("        or a")
e("        jp z,emit_next")
e("        ld hl,(bl_srcrow)")
e("        ld b,(hl)")
e("        inc hl")
e("        ld c,(hl)")
e("        inc hl")
e("        ld d,(hl)")
e("        inc hl")
e("        ld e,(hl)")
e("        ld h,#SPREADHI")
for k in range(8):
    e("        xor a")
    for r in ("b", "c", "d", "e"):
        e("        srl %s" % r)
        e("        rla")
    e("        ld l,a")
    e("        ld a,(hl)")
    e("        ld (bl_rows+%d),a" % k)
e("        ld a,0(iy)")
e("        bit 0,a")
e("        jr z,emit_no_low")
e("        ld de,(bl_alo)")
e("        ld hl,#bl_rows")
e("        call push_tile")
e("emit_no_low:")
e("        ld a,0(iy)")
e("        bit 1,a")
e("        jr z,emit_next")
e("        ld de,(bl_ahi)")
e("        ld hl,#bl_rows+4")
e("        call push_tile")
e("emit_next:")
e("        ld hl,(bl_srcrow)")
e("        ld de,#4")
e("        add hl,de")
e("        ld (bl_srcrow),hl")
e("        ld hl,(bl_alo)")
e("        ld de,#32")
e("        add hl,de")
e("        ld (bl_alo),hl")
e("        ld hl,(bl_ahi)")
e("        add hl,de")
e("        ld (bl_ahi),hl")
e("        inc iy")
e("        ld a,(bl_cnt)")
e("        dec a")
e("        ld (bl_cnt),a")
e("        jp nz,emit_col")
e("        ret")
e()

# ---------------------------------------------------------------------------
# push_tile:  DE = VRAM write address of the tile, HL -> 4 row bytes.
# Writes plane 0 of all 8 tile rows (each source row duplicated vertically).
# Interrupts are masked so nothing can touch the VDP between address bytes.
# ---------------------------------------------------------------------------
e("push_tile:")
e("        di")
for i in range(8):
    off = i * 4
    e("        ld a,e")
    if off:
        e("        add a,#%d" % off)
    e("        out (VDPCTRL),a")
    e("        ld a,d")
    e("        out (VDPCTRL),a")
    e("        ld a,(hl)")
    e("        out (VDPDATA),a")
    if i & 1 and i != 7:
        e("        inc hl")
e("        ei")
e("        ld hl,(_blitTileCount)")
e("        inc hl")
e("        ld (_blitTileCount),hl")
e("        ret")
e()

e("page_addr_tbl:")
for p in range(FB_PAGES):
    lo = VRAM_BASE + (2 * p) * ROW_STRIDE
    hi = lo + ROW_STRIDE
    e("        .dw #0x%04X" % lo)
    e("        .dw #0x%04X" % hi)
e()

path = sys.argv[1] if len(sys.argv) > 1 else "src/blit.s"
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote %s  (%d tiles, %dx%d)" % (path, TILES_X * TILES_Y, TILES_X, TILES_Y))
