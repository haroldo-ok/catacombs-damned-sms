#!/usr/bin/env python3
"""
Converts the Arduboy3D PROGMEM art/LUT/sound blobs into plain C arrays that
SDCC can place in the Z80's unified address space (no pgm_read_* needed).

Reads   : $ARDUBOY/Source/Arduboy3D/{Generated/SpriteData.inc.h, LUT.h,
                                     Textures.h, Sounds.cpp}
Writes  : src/gamedata.c  +  src/gamedata.h
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/home/user/Arduboy3D/Source/Arduboy3D"
OUTC = "src/gamedata.c"
OUTH = "src/gamedata.h"


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def parse_arrays(text):
    """-> list of (ctype, name, [values as strings]) in source order"""
    text = strip_comments(text)
    result = []
    pattern = re.compile(
        r"(?:extern\s+)?const\s+(uint8_t|uint16_t|int16_t)\s+"
        r"(?:Sounds::)?(\w+)\s*\[\]\s*(?:PROGMEM\s*)?=\s*\{(.*?)\}\s*;",
        re.S)
    for m in pattern.finditer(text):
        ctype, name, body = m.group(1), m.group(2), m.group(3)
        vals = [v.strip() for v in body.split(",") if v.strip()]
        result.append((ctype, name, vals))
    return result


CTYPE = {
    "uint8_t": "unsigned char",
    "uint16_t": "unsigned int",
    "int16_t": "signed int",
}


def emit(fc, fh, ctype, name, vals, per_line=16):
    fh.write("extern const %s %s[%d];\n" % (CTYPE[ctype], name, len(vals)))
    fc.write("const %s %s[%d] = {\n" % (CTYPE[ctype], name, len(vals)))
    for i in range(0, len(vals), per_line):
        fc.write("    " + ",".join(vals[i:i + per_line]) + ",\n")
    fc.write("};\n\n")


def main():
    os.makedirs("src", exist_ok=True)
    fc = open(OUTC, "w")
    fh = open(OUTH, "w")

    fc.write("/* GENERATED by tools/gendata.py - do not edit.\n"
             " * Art, lookup tables and sound effects from jhhoward/Arduboy3D. */\n")
    fc.write('#include "gamedata.h"\n\n')
    fh.write("/* GENERATED by tools/gendata.py - do not edit. */\n")
    fh.write("#ifndef GAMEDATA_H\n#define GAMEDATA_H\n\n")

    # ---- sprites ----------------------------------------------------------
    sprite_src = open(os.path.join(SRC, "Generated/SpriteData.inc.h")).read()
    frames = dict(re.findall(r"constexpr uint8_t (\w+)_numFrames = (\d+);", sprite_src))
    fh.write("/* ---- sprite / font / texture art ---- */\n")
    for name, n in sorted(frames.items()):
        fh.write("#define %s_numFrames %s\n" % (name, n))
    fh.write("\n")
    for ctype, name, vals in parse_arrays(sprite_src):
        emit(fc, fh, ctype, name, vals)
    fh.write("\n")

    # ---- lookup tables ----------------------------------------------------
    fh.write("/* ---- lookup tables ---- */\n")
    for ctype, name, vals in parse_arrays(open(os.path.join(SRC, "LUT.h")).read()):
        emit(fc, fh, ctype, name, vals)
    fh.write("\n")

    # ---- vector wall textures --------------------------------------------
    fh.write("/* ---- vector wall textures ---- */\n")
    tex_names = []
    for ctype, name, vals in parse_arrays(open(os.path.join(SRC, "Textures.h")).read()):
        emit(fc, fh, ctype, name, vals)
        tex_names.append(name)
    fh.write("extern const unsigned char *const textures[%d];\n\n" % len(tex_names))
    fc.write("const unsigned char *const textures[%d] = {\n    %s\n};\n\n"
             % (len(tex_names), ", ".join(tex_names)))

    # ---- sound effects ----------------------------------------------------
    fh.write("/* ---- ArduboyTones sound effects (frequency, ms) pairs ---- */\n")
    snd = open(os.path.join(SRC, "Sounds.cpp")).read()
    snd = snd.replace("TONES_END", "0x8000")
    for ctype, name, vals in parse_arrays(snd):
        emit(fc, fh, ctype, "Sound_" + name, vals)

    fh.write("\n#endif /* GAMEDATA_H */\n")
    fc.close()
    fh.close()
    print("wrote %s and %s" % (OUTC, OUTH))


main()
